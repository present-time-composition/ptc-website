#!/usr/bin/perl
# Adds/refreshes the description, share (Open Graph) tags and tab icons in every page's <head>.
# Run from the website folder:  perl tools/meta.pl
# When the site moves to its own domain, change $BASE below and run it again.
use strict; use warnings; use utf8;
binmode STDOUT, ':utf8';

my $BASE = 'https://present-time-composition.github.io/ptc-website/';

my %pages = (
  ''                                    => ['home',         'Present-Time Composition (PTC) is a method of improvisation developed by Alan Bern. By attending closely to inner impulses, improvisers learn to act in the moment together, creating meaningful musical content and form.'],
  'about-ptc/'                          => ['about-ptc',    'What Present-Time Composition (PTC) is, how it works, and how Alan Bern began developing it in 2005.'],
  'testimonies/'                        => ['testimonies',  'Musicians and artists describe what Present-Time Composition (PTC) has meant for their work.'],
  'deep-dive/'                          => ['deep-dive',    'An archive of texts, videos and recordings about Present-Time Composition (PTC).'],
  'contact/'                            => ['contact',      'Get in touch about Present-Time Composition (PTC): workshops, collaborations and questions.'],
  'past/'                               => ['past',         'Past PTC projects: Cincinnati Real-Time Composers, PTC @ Belvedere, PTC Dance and the PTC Music Advanced Lab.'],
  'past/cincinnati-real-time-composers/'=> ['cincinnati',   'Cincinnati Real-Time Composers, the first PTC student group at the University of Cincinnati: recordings and testimonies.'],
  'past/ptc-at-belvedere/'              => ['belvedere',    'PTC @ Belvedere: photos from Present-Time Composition with young musicians.'],
  'past/ptc-dance/'                     => ['dance',        'PTC Dance: Present-Time Composition for dancers and choreographers. Photos, video and lab notes.'],
  'past/ptc-music-advanced-lab/'        => ['advanced-lab', 'PTC Music Advanced Lab, a research workshop in Berlin, April 2017: photos and workshop clips.'],
  'future/'                             => ['future',       'Upcoming Present-Time Composition (PTC) events and workshops.'],
  'future/ptc-erasmus-youth-exchange-2027/' => ['erasmus-2027', 'PTC Erasmus+ Youth Exchange, 18–28 February 2027 at The Other Music Academy in Weimar: ten days of improvisation and movement for musicians and vocalists aged 18–30 from Germany, Austria and Finland.'],
  'impressum/'                          => ['home',         'Impressum / legal notice for the present-time composition website.'],
  'datenschutz/'                        => ['home',         'Datenschutzerklärung / privacy policy for the present-time composition website.'],
);

sub esc { my $s = shift; $s =~ s/&/&amp;/g; $s =~ s/"/&quot;/g; $s =~ s/</&lt;/g; return $s; }

for my $rel (sort keys %pages) {
  my $file = "docs/${rel}index.html";
  open my $in, '<:encoding(UTF-8)', $file or die "$file: $!"; local $/; my $html = <$in>; close $in;
  my ($share, $desc) = @{ $pages{$rel} };
  my ($title) = $html =~ m{<title>(.*?)</title>}s;
  my $depth = () = $rel =~ m{/}g; my $up = '../' x $depth;
  my $block = join "\n",
    '  <!-- meta:start (generated by tools/meta.pl) -->',
    '  <meta name="description" content="' . esc($desc) . '">',
    '  <meta property="og:type" content="website">',
    '  <meta property="og:site_name" content="present-time composition">',
    '  <meta property="og:title" content="' . esc($title) . '">',
    '  <meta property="og:description" content="' . esc($desc) . '">',
    '  <meta property="og:url" content="' . $BASE . $rel . '">',
    '  <meta property="og:image" content="' . $BASE . "images/share/$share.jpg" . '">',
    '  <meta property="og:image:width" content="1200">',
    '  <meta property="og:image:height" content="630">',
    '  <meta name="twitter:card" content="summary_large_image">',
    '  <link rel="icon" href="' . $up . 'favicon.svg" type="image/svg+xml">',
    '  <link rel="icon" href="' . $up . 'favicon-32.png" sizes="32x32" type="image/png">',
    '  <link rel="apple-touch-icon" href="' . $up . 'apple-touch-icon.png">',
    '  <!-- meta:end -->';
  $html =~ s{\n  <!-- meta:start.*?<!-- meta:end -->}{}s;   # replace an earlier block
  $html =~ s{(</title>)}{$1\n$block};
  open my $out, '>:encoding(UTF-8)', $file or die $!; print $out $html; close $out;
  print "$rel -> $share\n";
}
